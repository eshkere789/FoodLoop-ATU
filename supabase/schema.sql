-- ========== ТАБЛИЦЫ ==========
create table if not exists organizations (
  org_id int primary key,
  organization text not null,
  org_type text not null,
  is_lab boolean not null default false,
  can_sell boolean not null default true,
  building text,
  pickup_from text,
  pickup_to text,
  responsible_user_id int,
  is_active boolean not null default true,
  qr_slug text unique not null,
  form_url text,
  permit_valid_until date,
  permit_status text,
  permit_supervisor text,
  default_discount_pct int
);

create table if not exists users (
  user_id int primary key,
  full_name text not null,
  role text not null check (role in ('responsible','reviewer','admin','management','buyer')),
  role_ru text,
  org_id int references organizations(org_id),
  login text unique not null,
  auth_id uuid unique
);

create table if not exists products (
  product_id int primary key,
  product text not null,
  waste_type text not null,
  price_full_kzt int not null default 0,
  portion_kg numeric not null default 0.2,
  composition text,
  allergens text,
  is_sellable boolean not null default true,
  is_lab_product boolean not null default false
);

create table if not exists reports (
  report_id int generated by default as identity primary key,
  org_id int not null references organizations(org_id),
  report_date date not null,
  status text not null check (status in ('draft','submitted','under_review','accepted','returned')),
  submitted_by int references users(user_id),
  reviewed_by int references users(user_id),
  submitted_at timestamp,
  reviewed_at timestamp,
  reviewer_comment text
);
create index if not exists idx_reports_date on reports(report_date);
create index if not exists idx_reports_org on reports(org_id);
create index if not exists idx_reports_status on reports(status);

create table if not exists report_items (
  item_id int generated by default as identity primary key,
  report_id int not null references reports(report_id) on delete cascade,
  product_id int not null references products(product_id),
  quantity_kg numeric not null check (quantity_kg > 0),
  portions int not null check (portions > 0),
  discount_reason text not null,
  shelf_days_left int not null check (shelf_days_left >= 0),
  is_listed boolean not null default false,
  price_full_kzt int,
  price_discount_kzt int,
  discount_pct int,
  sold_portions int,
  sold_kg numeric,
  revenue_kzt int,
  wasted_kg numeric,
  recyclable_pct int,
  co2e_wasted_kg numeric,
  co2e_avoided_kg numeric
);
create index if not exists idx_items_report on report_items(report_id);

create table if not exists bookings (
  booking_id int generated by default as identity primary key,
  item_id int not null references report_items(item_id) on delete cascade,
  user_id int not null references users(user_id),
  portions int not null check (portions > 0),
  status text not null check (status in ('booked','collected','no_show','cancelled')),
  booked_at timestamp not null default now(),
  pickup_date date,
  pickup_code text
);
create index if not exists idx_bookings_item on bookings(item_id);
create index if not exists idx_bookings_user on bookings(user_id);

create table if not exists feedback (
  feedback_id int generated by default as identity primary key,
  booking_id int not null unique references bookings(booking_id) on delete cascade,
  user_id int not null references users(user_id),
  org_id int not null references organizations(org_id),
  item_id int not null references report_items(item_id) on delete cascade,
  rating int not null check (rating between 1 and 5),
  category text,
  comment text,
  created_at timestamp not null default now(),
  reply text,
  replied_by int references users(user_id)
);

create table if not exists settings (key text primary key, value text not null);
