-- ========== ВНУТРЕННИЕ ФУНКЦИИ ==========
create or replace function _co2() returns numeric language sql stable as
$$ select coalesce((select value::numeric from settings where key='co2_factor'), 2.5) $$;

create or replace function _enqueue_user(p_user int, p_text text) returns void language sql as
$$ insert into outbox(chat_id, text) select chat_id, p_text from telegram_links where user_id = p_user and chat_id is not null $$;
create or replace function _enqueue_subscribers(p_text text) returns void language sql as
$$ insert into outbox(chat_id, text) select chat_id, p_text from telegram_links where subscribed and chat_id is not null $$;

create or replace function _recalc_item(p_item int) returns void language plpgsql as $$
declare v_sold int; v_kg numeric; f numeric := _co2();
begin
  select coalesce(sum(b.portions) filter (where b.status = 'collected'), 0) into v_sold from bookings b where b.item_id = p_item;
  update report_items i set
    sold_portions = v_sold,
    sold_kg = round(v_sold * p.portion_kg, 2),
    revenue_kzt = v_sold * coalesce(i.price_discount_kzt, 0),
    wasted_kg = round(i.quantity_kg - v_sold * p.portion_kg, 2),
    co2e_avoided_kg = round(v_sold * p.portion_kg * f, 2),
    co2e_wasted_kg = round((i.quantity_kg - v_sold * p.portion_kg) * f, 2)
  from products p where i.item_id = p_item and p.product_id = i.product_id;
end $$;

-- принять отчёт без проверки ролей (используется review_report и сидом)
create or replace function _accept_report(p_report int, p_reviewer int) returns jsonb language plpgsql as $$
declare r reports; o organizations; it record; v_pct int; v_price int; v_listed int := 0; v_skipped int := 0;
        v_can boolean; f numeric := _co2(); v_rec int;
begin
  select * into r from reports where report_id = p_report;
  select * into o from organizations where org_id = r.org_id;
  update reports set status = 'accepted', reviewed_by = p_reviewer, reviewed_at = now(), reviewer_comment = null where report_id = p_report;
  for it in select i.*, p.is_sellable, p.price_full_kzt as p_price, p.waste_type from report_items i join products p using (product_id) where i.report_id = p_report loop
    v_can := o.can_sell and it.is_sellable and it.p_price > 0
             and (not o.is_lab or (o.permit_valid_until is not null and o.permit_valid_until >= r.report_date));
    v_rec := case when not o.can_sell then 100 else case it.waste_type when 'хлебобулочные' then 70 when 'выпечка' then 60
              when 'овощи и фрукты' then 90 when 'готовые блюда' then 40 when 'молочные продукты' then 30 else 50 end end;
    if v_can then
      v_pct := case when o.is_lab then coalesce(o.default_discount_pct, 55)
                    else case it.discount_reason when 'Срок годности истекает сегодня' then 55 when 'Срок годности истекает завтра' then 40
                         when 'Остаток после обеда' then 45 when 'Излишки поставки' then 35 else 30 end end;
      v_price := (round(it.p_price * (1 - v_pct / 100.0) / 10) * 10)::int;
      v_pct := round((1 - v_price::numeric / it.p_price) * 100);
      v_listed := v_listed + 1;
    else
      v_price := null; v_pct := null; v_skipped := v_skipped + 1;
    end if;
    update report_items set is_listed = v_can, price_full_kzt = it.p_price, price_discount_kzt = v_price, discount_pct = v_pct,
      sold_portions = 0, sold_kg = 0, revenue_kzt = 0, wasted_kg = it.quantity_kg, recyclable_pct = v_rec,
      co2e_wasted_kg = round(it.quantity_kg * f, 2), co2e_avoided_kg = 0 where item_id = it.item_id;
  end loop;
  if v_listed > 0 then
    perform _enqueue_subscribers('Новые лоты со скидкой: ' || o.organization || ' (' || v_listed || ' поз.). Откройте витрину FoodLoop.');
  end if;
  return jsonb_build_object('listed', v_listed, 'skipped', v_skipped);
end $$;

-- ========== RPC (вызываются с клиента) ==========
create or replace function submit_report(p_report jsonb) returns int language plpgsql security definer set search_path = public as $$
declare v_role text := app_role(); v_uid int := app_user_id(); v_org int := (p_report->>'org_id')::int;
        v_id int := nullif(p_report->>'report_id','')::int; v_draft boolean := coalesce((p_report->>'draft')::boolean, false);
        v_status text; x jsonb; ex reports;
begin
  if v_role not in ('responsible','admin') then raise exception 'Нет прав на подачу отчёта'; end if;
  if v_role = 'responsible' and v_org is distinct from app_org_id() then raise exception 'Можно подавать отчёты только своей организации'; end if;
  if jsonb_array_length(coalesce(p_report->'items','[]'::jsonb)) = 0 then raise exception 'Добавьте хотя бы одну позицию'; end if;
  v_status := case when v_draft then 'draft' else 'submitted' end;
  if v_id is not null then
    select * into ex from reports where report_id = v_id;
    if not found or ex.org_id <> v_org then raise exception 'Отчёт не найден'; end if;
    if ex.status not in ('draft','returned') then raise exception 'Отчёт уже на проверке или принят'; end if;
    update reports set status = v_status, report_date = (p_report->>'report_date')::date, submitted_by = v_uid,
      submitted_at = case when v_draft then null else now() end, reviewed_by = null, reviewed_at = null, reviewer_comment = null where report_id = v_id;
    delete from report_items where report_id = v_id;
  else
    insert into reports(org_id, report_date, status, submitted_by, submitted_at)
    values (v_org, (p_report->>'report_date')::date, v_status, v_uid, case when v_draft then null else now() end) returning report_id into v_id;
  end if;
  for x in select * from jsonb_array_elements(p_report->'items') loop
    insert into report_items(report_id, product_id, quantity_kg, portions, discount_reason, shelf_days_left, price_full_kzt)
    values (v_id, (x->>'product_id')::int, (x->>'quantity_kg')::numeric, (x->>'portions')::int, x->>'discount_reason',
            (x->>'shelf_days_left')::int, (select price_full_kzt from products where product_id = (x->>'product_id')::int));
  end loop;
  return v_id;
end $$;

create or replace function take_review(p_report int) returns void language plpgsql security definer set search_path = public as $$
begin
  if app_role() not in ('reviewer','admin') then raise exception 'Нет прав'; end if;
  update reports set status = 'under_review' where report_id = p_report and status = 'submitted';
end $$;

create or replace function review_report(p_report int, p_decision text, p_comment text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare r reports; v_res jsonb;
begin
  if app_role() not in ('reviewer','admin') then raise exception 'Нет прав на проверку'; end if;
  select * into r from reports where report_id = p_report for update;
  if not found then raise exception 'Отчёт не найден'; end if;
  if r.status not in ('submitted','under_review') then raise exception 'Отчёт уже обработан'; end if;
  if p_decision = 'accepted' then
    v_res := _accept_report(p_report, app_user_id());
    return v_res;
  elsif p_decision = 'returned' then
    if coalesce(trim(p_comment), '') = '' then raise exception 'Укажите комментарий при возврате'; end if;
    update reports set status = 'returned', reviewed_by = app_user_id(), reviewed_at = now(), reviewer_comment = p_comment where report_id = p_report;
    perform _enqueue_user(r.submitted_by, 'Отчёт №' || p_report || ' возвращён: ' || p_comment);
    return jsonb_build_object('returned', true);
  else raise exception 'Неизвестное решение';
  end if;
end $$;

create or replace function create_booking(p_item int, p_portions int) returns bookings language plpgsql security definer set search_path = public as $$
declare i report_items; r reports; v_taken int; v_rem int; b bookings; v_code text; v_name text;
begin
  if app_role() not in ('buyer','admin') then raise exception 'Бронировать могут только покупатели'; end if;
  if p_portions is null or p_portions < 1 then raise exception 'Укажите количество порций'; end if;
  select * into i from report_items where item_id = p_item for update;
  if not found then raise exception 'Лот не найден'; end if;
  select * into r from reports where report_id = i.report_id;
  if r.status <> 'accepted' or not i.is_listed or r.report_date < current_date then raise exception 'Лот недоступен для брони'; end if;
  select coalesce(sum(portions), 0) into v_taken from bookings where item_id = p_item and status in ('booked','collected');
  v_rem := i.portions - v_taken;
  if p_portions > v_rem then raise exception 'Недостаточно порций: осталось %', v_rem; end if;
  v_code := lpad((floor(random() * 900000) + 100000)::int::text, 6, '0');
  insert into bookings(item_id, user_id, portions, status, pickup_date, pickup_code)
  values (p_item, app_user_id(), p_portions, 'booked', r.report_date, v_code) returning * into b;
  select product into v_name from products where product_id = i.product_id;
  perform _enqueue_user(app_user_id(), 'Бронь подтверждена: ' || v_name || ' x' || p_portions || '. Код выдачи ' || v_code);
  return b;
end $$;

create or replace function cancel_booking(p_booking int) returns void language plpgsql security definer set search_path = public as $$
begin
  update bookings set status = 'cancelled' where booking_id = p_booking and user_id = app_user_id() and status = 'booked';
  if not found then raise exception 'Бронь не найдена или уже обработана'; end if;
end $$;

create or replace function mark_booking(p_booking int, p_status text) returns void language plpgsql security definer set search_path = public as $$
declare b bookings; v_org int;
begin
  if p_status not in ('collected','no_show') then raise exception 'Недопустимый статус'; end if;
  select * into b from bookings where booking_id = p_booking for update;
  if not found then raise exception 'Бронь не найдена'; end if;
  select r.org_id into v_org from report_items i join reports r using (report_id) where i.item_id = b.item_id;
  if not (app_role() = 'admin' or (app_role() = 'responsible' and app_org_id() = v_org)) then raise exception 'Нет прав'; end if;
  if b.status <> 'booked' then raise exception 'Бронь уже обработана'; end if;
  update bookings set status = p_status where booking_id = p_booking;
  perform _recalc_item(b.item_id);
end $$;

create or replace function add_feedback(p_booking int, p_rating int, p_category text, p_comment text) returns void
language plpgsql security definer set search_path = public as $$
declare b bookings; v_org int;
begin
  select * into b from bookings where booking_id = p_booking;
  if not found or b.user_id <> app_user_id() then raise exception 'Бронь не найдена'; end if;
  if b.status <> 'collected' then raise exception 'Отзыв можно оставить после получения заказа'; end if;
  if exists (select 1 from feedback where booking_id = p_booking) then raise exception 'Отзыв уже оставлен'; end if;
  select r.org_id into v_org from report_items i join reports r using (report_id) where i.item_id = b.item_id;
  insert into feedback(booking_id, user_id, org_id, item_id, rating, category, comment) values (p_booking, b.user_id, v_org, b.item_id, p_rating, p_category, p_comment);
end $$;

create or replace function reply_feedback(p_feedback int, p_reply text) returns void language plpgsql security definer set search_path = public as $$
declare f feedback;
begin
  select * into f from feedback where feedback_id = p_feedback;
  if not found then raise exception 'Отзыв не найден'; end if;
  if not (app_role() = 'admin' or (app_role() = 'responsible' and app_org_id() = f.org_id)) then raise exception 'Нет прав'; end if;
  update feedback set reply = p_reply, replied_by = app_user_id() where feedback_id = p_feedback;
end $$;

create or replace function create_tg_code() returns text language plpgsql security definer set search_path = public as $$
declare v_code text := lpad((floor(random() * 900000) + 100000)::int::text, 6, '0');
begin
  if app_user_id() is null then raise exception 'Нужен вход'; end if;
  insert into telegram_links(user_id, link_code) values (app_user_id(), v_code)
  on conflict (user_id) do update set link_code = excluded.link_code;
  return v_code;
end $$;

