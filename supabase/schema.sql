-- после импорта CSV: выровнять счётчики идентификаторов
create or replace function reset_sequences() returns void language plpgsql as $$
begin
  perform setval(pg_get_serial_sequence('reports','report_id'), coalesce((select max(report_id) from reports),0)+1, false);
  perform setval(pg_get_serial_sequence('report_items','item_id'), coalesce((select max(item_id) from report_items),0)+1, false);
  perform setval(pg_get_serial_sequence('bookings','booking_id'), coalesce((select max(booking_id) from bookings),0)+1, false);
  perform setval(pg_get_serial_sequence('feedback','feedback_id'), coalesce((select max(feedback_id) from feedback),0)+1, false);
end $$;

