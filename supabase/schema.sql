create or replace view v_lots as
select i.item_id, r.org_id, o.organization, o.building, o.pickup_from, o.pickup_to, o.is_lab,
       p.product, p.composition, p.allergens, p.portion_kg, i.price_full_kzt, i.price_discount_kzt, i.discount_pct,
       i.shelf_days_left, i.discount_reason, i.portions, i.portions - coalesce(b.taken, 0) as remaining, r.report_date
from report_items i
join reports r on r.report_id = i.report_id
join organizations o on o.org_id = r.org_id
join products p on p.product_id = i.product_id
left join lateral (select sum(portions) as taken from bookings where item_id = i.item_id and status in ('booked','collected')) b on true
where r.status = 'accepted' and i.is_listed and r.report_date >= current_date;

create or replace view v_facts as
select i.item_id, r.report_id, r.report_date, to_char(r.report_date, 'YYYY-MM') as month, (extract(isodow from r.report_date)::int - 1) as weekday,
       r.org_id, o.organization, o.org_type, o.is_lab, p.product, p.waste_type, i.discount_reason, i.shelf_days_left,
       i.quantity_kg, i.portions, i.is_listed, i.price_discount_kzt, i.sold_portions, i.sold_kg, i.revenue_kzt, i.wasted_kg,
       i.recyclable_pct, i.co2e_wasted_kg, i.co2e_avoided_kg, r.status
from report_items i
join reports r on r.report_id = i.report_id
join organizations o on o.org_id = r.org_id
join products p on p.product_id = i.product_id
where r.status = 'accepted'
  and (app_role() in ('reviewer','admin','management') or (app_role() = 'responsible' and r.org_id = app_org_id()));

create or replace view v_bookings as
select b.booking_id, b.item_id, b.user_id, u.full_name as buyer, b.portions, b.status, b.booked_at, b.pickup_date, b.pickup_code,
       p.product, o.organization, o.building, o.pickup_from, o.pickup_to, r.org_id, i.price_discount_kzt,
       (select count(*) from feedback f where f.booking_id = b.booking_id) as has_feedback
from bookings b
join users u on u.user_id = b.user_id
join report_items i on i.item_id = b.item_id
join reports r on r.report_id = i.report_id
join organizations o on o.org_id = r.org_id
join products p on p.product_id = i.product_id
where b.user_id = app_user_id()
   or app_role() in ('reviewer','admin','management')
   or (app_role() = 'responsible' and r.org_id = app_org_id());

create or replace view v_feedback as
select f.feedback_id, f.booking_id, f.org_id, o.organization, p.product, f.rating, f.category, f.comment, f.created_at, f.reply,
       (f.user_id = app_user_id()) as is_mine
from feedback f
join organizations o on o.org_id = f.org_id
join report_items i on i.item_id = f.item_id
join products p on p.product_id = i.product_id
where f.user_id = app_user_id()
   or app_role() in ('reviewer','admin','management')
   or (app_role() = 'responsible' and f.org_id = app_org_id());

create or replace view v_monthly as
select month, sum(quantity_kg) as quantity_kg, sum(sold_kg) as sold_kg, sum(wasted_kg) as wasted_kg,
       sum(revenue_kzt) as revenue_kzt, sum(co2e_avoided_kg) as co2e_avoided_kg
from v_facts group by month order by month;

